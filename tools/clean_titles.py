CHESS = re.compile(OPENINGS + r'|[车馬马炮兵卒相象士仕帅将][一二三四五六七八九1-9][进退平][一二三四五六七八九1-9]|(?:[单双一二三四五六七八九十老前后左右中底边]{0,2}[车马炮兵卒士仕帅将]){2,}')

def clean_title(title):
    t = unicodedata.normalize('NFKC', title).split('#')[0]
    t = re.sub(r'河南省(?:三届)?(?:象棋)?冠(?:军)?黄丹青(?:老师)?(?:全套象棋课程)?', '', t)
    t = re.sub(r'(?:象棋)?布局一点通(?:全套课程)?|黄丹青(?:全套)?(?:象棋)?课程|象棋黄丹青课程', '', t)
    t = re.sub(r'如何(?:快速提升|快速象棋|提升象棋|学习(?:象棋)?布|系统学习象棋|系统学棋)[^!！?？。]*[!！?？。]?', '', t)
    t = re.sub(r'真心教棋|少走弯路|带你上业九|不上业九不罢休|零基础教学', '', t)
    t = re.sub(r'(?:私信|买课|购课)[^!！?？。]*[!！?？。]?', '', t)
    t = re.sub(r'\(?实战加(?:天花板的)?复盘\)?|\(?实战复盘\)?|\(?复盘分析\)?|\(?复盘\)?|\(?实战\)?', '', t)
    t = re.sub(r'\d+\s*[-:比]\s*\d+', '', t)
    t = re.sub(r'绝招.*?还是天天中刀.*$', '', t)
    t = t.replace('诱使其打车的绝妙思路', '诱使打车').replace('诱使其打车', '诱使打车')
    t = re.sub(r'一局棋|之', '', t)
    t = re.sub(r'的?(?:绝妙思路|绝妙招法|绝妙手段|绝妙招数|绝招|高级陷阱|万能招法|万能布局|大套路)', lambda m: '陷阱' if '陷阱' in m[0] else '', t)
    t = re.sub(r'深度解析|全解析|精彩讲解|棋理讲解|教学讲解|讲解|欣赏|秘传绝学|密传绝学|密传教程|绝密教程', '', t)
    t = re.sub(r'(?:各种|所有|各路)(?:布局)?变化', '变化', t)
    t = re.sub(r'又来啦|来啦|没朋友|必输无疑|简单粗暴|超级实用|简单易学|轻松(?:赢棋|速胜|占优|取胜)|紧张刺激|跌宕起伏|精妙绝伦|酣畅淋漓', '', t)
    t = re.sub(r'一个视频|超长干货分享|超长干货|确实厉害|只需一招|只要一招|照样可以用|赢棋第一定律|每一步都智慧无穷|每一步都讲[的得]明明白白', '', t)
    t = re.sub(r'绝密不外传的|新手必看的?|高手必看的?|免费分享|课程|最后', '', t)
    t = re.sub(r'^(?:肺腑之言[:：]?|学棋先学|学会|教你|带你|只要|一个飞刀搞定|一步棋破|如何)', '', t)
    t = re.sub(r'花钱都买不到的?|他们不会.*|会了也不告诉你.*|让你知其然.*|你(?:一定|也|知道|能看).*|学会这个.*|刷到就是赚到.*|这是什么水平.*|究竟哪里.*', '', t)
    clauses = []
    for c in re.split(r'[，,。.!！?？;；:：\n]+', t):
        c = c.strip(' ()（）“”「」【】《》—-')
        c = re.sub(r'^(?:学棋先学|教你|如何|什么是|何为|两分钟教会你|一分钟教会你|三分钟教会你)', '', c)
        c = re.sub(r'^(?:臭棋乱|一招棋|一招|妙手|终于明白了)', '', c)
        c = re.sub(r'(?:试试|算啥|为什么|为何|怎么|你一定|你也经常).*$', '', c) if not re.search(r'(?:为什么|为何).*(?:炮|马|车|兵|卒|士|相)', c) else c
        c = re.sub(r'(?:开局就|只用|只需|就可|可以|又该)', '', c)
        c = re.sub(r'(?:还是天天中刀|错一步就速败|必败的这路变化|的死穴终于找到了|开局就速败).*$', '', c)
        c = re.sub(r'的?(?:关键要领|关键之招|关键招法|速胜招法|速胜|攻防要领|后续手段|常用手段|进攻思路|防守要领|优缺点|演变历程)', lambda m: m[0].lstrip('的'), c)
        c = re.sub(r'(?:的)?(?:绝妙|精妙|必学|必修|常见|正确的|最最最正确的|最最正确的|唯一正确的|不常见的)', '', c)
        if not CHESS.search(c):
            continue
        # Long rhetorical clauses retain their concrete named formations and moves.
        if len(c) > 30 or re.search(r'你|咱|棋友|高手|对手研究|业九|业八|软件主播|一代宗师|我敢|重蹈|直播.*年|只需|只要|居然|到底|终于明白|天花板|百分|100分|课程里|布局都是|其他布局|这才是|轻松|必败|只有|对手.*(?:还|就|不)|死背|学会|涨棋|赢棋|厉害|开局即结局|不懂|这路变化|这种|大哥|战到|的秘诀|一个立刻|对手的', c):
            names = list(dict.fromkeys(m[0] for m in CHESS.finditer(c)))
            c = '、'.join(names)
        c = c.strip('的 ()（）—-')
        if c and c not in clauses:
            clauses.append(c)
    return '，'.join(clauses) or '未注明着法'
